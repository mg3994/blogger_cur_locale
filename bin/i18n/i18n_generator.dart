import 'dart:convert';
import 'dart:io';
import 'package:path/path.dart' as p;
import 'i18n_config.dart';

/// Generates the client-side JavaScript internationalization dictionary and helpers,
/// and automatically generates the type-safe Dart AppInternationalization class.
String generateI18nScript() {
  final l10nDir = Directory('l10n');
  final Map<String, Map<String, String>> dictionary = {};
  final Map<String, String> defaultTranslations = {};

  if (l10nDir.existsSync()) {
    final files = l10nDir.listSync().whereType<File>();
    for (final file in files) {
      final name = p.basename(file.path);
      if (name.endsWith('.arb')) {
        try {
          final content = file.readAsStringSync();
          final data = json.decode(content);
          if (data is Map) {
            final locale = data['@@locale'] ?? name.replaceAll('intl_', '').replaceAll('.arb', '');

            if (I18nConfig.supportedLocales.contains(locale)) {
              final Map<String, String> translations = {};
              for (final entry in data.entries) {
                final key = entry.key;
                final value = entry.value;
                if (!key.startsWith('@') && value is String) {
                  translations[key] = value;
                  if (locale == I18nConfig.defaultLocale) {
                    defaultTranslations[key] = value;
                  }
                }
              }
              dictionary[locale] = translations;
            }
          }
        } catch (e) {
          print('Warning: Failed to parse ARB file ${file.path}: $e');
        }
      }
    }
  }

  // Ensure default fallback translations are present
  if (dictionary.isEmpty || defaultTranslations.isEmpty) {
    defaultTranslations['session_settings'] = 'Session Settings';
    dictionary[I18nConfig.fallbackLocale] = defaultTranslations;
  }

  // Write type-safe Dart localization file
  _generateDartAppInternationalization(dictionary, defaultTranslations);

  final dictionaryJson = json.encode(dictionary);
  final currencySymbolsJson = json.encode(I18nConfig.currencySymbols);

  // Generate type-safe named JS methods on AppI18n for each key
  final StringBuffer jsMethods = StringBuffer();
  for (final key in defaultTranslations.keys) {
    jsMethods.writeln('''
    $key: function(vars) {
      return this.translate('$key', vars);
    },''');
  }

  return '''
(function() {
  const i18nDictionary = $dictionaryJson;
  const rtlLocales = ['ar', 'he', 'fa', 'ur', 'syr', 'dv', 'yi'];

  // Global AppI18n Engine
  window.AppI18n = {
    getLocale: function() {
      return localStorage.getItem('antinna-locale') || '${I18nConfig.defaultLocale}';
    },

    getCurrency: function() {
      return localStorage.getItem('antinna-currency') || '${I18nConfig.defaultCurrency}';
    },

    // 1. Core Translation with recursive ICU Message formatting
    translate: function(key, vars = {}) {
      const locale = this.getLocale();
      const dict = i18nDictionary[locale] || i18nDictionary['${I18nConfig.fallbackLocale}'] || {};
      const msg = dict[key] || i18nDictionary['${I18nConfig.fallbackLocale}'][key] || key;
      return this.formatMessage(msg, vars);
    },

    // Autogenerated typed methods on AppI18n for ARB keys
$jsMethods

    // ICU Message recursive parser supporting variables, plurals, and selects
    formatMessage: function(msg, vars = {}) {
      if (typeof msg !== 'string') return '';

      const self = this;
      function parse(text) {
        let openBrace = -1;
        let braceCount = 0;
        for (let i = 0; i < text.length; i++) {
          if (text[i] === '{') {
            if (braceCount === 0) openBrace = i;
            braceCount++;
          } else if (text[i] === '}') {
            braceCount--;
            if (braceCount === 0 && openBrace !== -1) {
              const inner = text.substring(openBrace + 1, i);
              const prefix = text.substring(0, openBrace);
              const suffix = text.substring(i + 1);
              const result = evaluateExpression(inner, vars);
              return parse(prefix + result + suffix);
            }
          }
        }
        return text;
      }

      function evaluateExpression(expr, variables) {
        const parts = expr.split(',');
        const varName = parts[0].trim();
        if (parts.length === 1) {
          return variables[varName] !== undefined ? variables[varName] : '{' + varName + '}';
        }

        const type = parts[1].trim();
        const remaining = parts.slice(2).join(',').trim();

        if (type === 'plural' || type === 'select') {
          const cases = {};
          let caseOpen = -1;
          let caseBraceCount = 0;
          let currentCaseName = '';

          for (let i = 0; i < remaining.length; i++) {
            if (remaining[i] === '{') {
              if (caseBraceCount === 0) {
                caseOpen = i;
                currentCaseName = remaining.substring(0, i).trim();
              }
              caseBraceCount++;
            } else if (remaining[i] === '}') {
              caseBraceCount--;
              if (caseBraceCount === 0 && caseOpen !== -1) {
                cases[currentCaseName] = remaining.substring(caseOpen + 1, i);
                caseOpen = -1;
              }
            }
          }

          const val = variables[varName];
          if (type === 'plural') {
            const exactCase = '=' + val;
            if (cases[exactCase] !== undefined) {
              return parse(cases[exactCase].replace(new RegExp('\\\\{' + varName + '\\\\}', 'g'), val));
            }

            const locale = self.getLocale();
            const pr = new Intl.PluralRules(locale);
            const rule = pr.select(val);

            if (cases[rule] !== undefined) {
              return parse(cases[rule].replace(new RegExp('\\\\{' + varName + '\\\\}', 'g'), val));
            }
            return parse(cases['other'] || '');
          } else {
            // select
            if (cases[val] !== undefined) {
              return parse(cases[val]);
            }
            return parse(cases['other'] || '');
          }
        }
        return '{' + expr + '}';
      }

      return parse(msg);
    },

    // 2. ICU Number, Percentage & Scientific Formatting
    formatDecimal: function(val, fractionDigits = 2) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, {
        minimumFractionDigits: fractionDigits,
        maximumFractionDigits: fractionDigits
      }).format(val);
    },

    formatCompact: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { notation: 'compact' }).format(val);
    },

    formatPercent: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { style: 'percent' }).format(val);
    },

    formatScientific: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { notation: 'scientific' }).format(val);
    },

    // 3. Currency & Financial Formatting
    formatCurrency: function(val, currencyCode) {
      const locale = this.getLocale();
      const code = currencyCode || this.getCurrency();
      return new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: code
      }).format(val);
    },

    // 4. ICU Date & Time Formatting
    formatDate: function(date, options = { year: 'numeric', month: 'long', day: 'numeric' }) {
      const locale = this.getLocale();
      const d = typeof date === 'string' || typeof date === 'number' ? new Date(date) : date;
      return new Intl.DateTimeFormat(locale, options).format(d);
    },

    formatTime: function(date, use24Hour = false) {
      const locale = this.getLocale();
      const d = typeof date === 'string' || typeof date === 'number' ? new Date(date) : date;
      return new Intl.DateTimeFormat(locale, {
        hour: 'numeric',
        minute: 'numeric',
        hour12: !use24Hour
      }).format(d);
    },

    formatRelativeTime: function(val, unit = 'day') {
      const locale = this.getLocale();
      return new Intl.RelativeTimeFormat(locale, { numeric: 'auto' }).format(val, unit);
    }
  };

  // Helper backward-compatibility reference
  window.AntinnaL10nHelper = {
    getLocale: function() { return window.AppI18n.getLocale(); },
    getCurrency: function() { return window.AppI18n.getCurrency(); },
    formatPrice: function(price, currency = null) { return window.AppI18n.formatCurrency(price, currency); }
  };

  window.translateDOM = function() {
    const currentLocale = localStorage.getItem('antinna-locale') || '${I18nConfig.defaultLocale}';
    const dict = i18nDictionary[currentLocale] || i18nDictionary['${I18nConfig.fallbackLocale}'] || {};

    // 1. Translate elements with data-i18n and data-i18n-vars
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        let vars = {};
        const varsAttr = el.getAttribute('data-i18n-vars');
        if (varsAttr) {
          try {
            vars = JSON.parse(varsAttr);
          } catch(e) {}
        }
        const translated = window.AppI18n.formatMessage(dict[key], vars);
        if (el.textContent !== translated) {
          el.textContent = translated;
        }
      }
    });

    // 2. Translate placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        if (el.getAttribute('placeholder') !== dict[key]) {
          el.setAttribute('placeholder', dict[key]);
        }
      }
    });

    // 3. Sync language selector values (both modal and sidebar)
    const langSelectors = ['language-selector', 'sidebar-language-selector'];
    langSelectors.forEach(id => {
      const select = document.getElementById(id);
      if (select && select.value !== currentLocale) {
        select.value = currentLocale;
      }
    });

    // 4. Sync currency selector values (both modal and sidebar)
    const currentCurrency = localStorage.getItem('antinna-currency') || '${I18nConfig.defaultCurrency}';
    const currSelectors = ['currency-selector', 'sidebar-currency-selector'];
    currSelectors.forEach(id => {
      const select = document.getElementById(id);
      if (select && select.value !== currentCurrency) {
        select.value = currentCurrency;
      }
    });
  };

  window.setLanguage = function(lang) {
    localStorage.setItem('antinna-locale', lang);
    document.documentElement.setAttribute('lang', lang);

    if (rtlLocales.indexOf(lang) !== -1) {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
    }

    window.translateDOM();

    // Callback hook for custom user logic
    if (typeof window.onCurrencyOrLocaleChange === 'function') {
      window.onCurrencyOrLocaleChange();
    }
  };

  window.setCurrency = function(curr) {
    localStorage.setItem('antinna-currency', curr);
    const htmlEl = document.documentElement;

    const classesToRemove = [];
    htmlEl.classList.forEach(cls => {
      if (cls.startsWith('currency-')) {
        classesToRemove.push(cls);
      }
    });
    classesToRemove.forEach(cls => htmlEl.classList.remove(cls));

    htmlEl.classList.add('currency-' + curr.toLowerCase());

    // Callback hook for custom user logic
    if (typeof window.onCurrencyOrLocaleChange === 'function') {
      window.onCurrencyOrLocaleChange();
    }
  };

  // Run on DOMContentLoaded and observe future mutations
  document.addEventListener('DOMContentLoaded', () => {
    window.translateDOM();
    if (typeof window.onCurrencyOrLocaleChange === 'function') {
      window.onCurrencyOrLocaleChange();
    }

    const observer = new MutationObserver(() => {
      window.translateDOM();
    });
    observer.observe(document.body, { childList: true, subtree: true });
  });
})();
''';
}

/// Dynamic Dart code generator for Flutter-style AppInternationalization class
void _generateDartAppInternationalization(Map<String, Map<String, String>> dictionary, Map<String, String> defaultTranslations) {
  final buffer = StringBuffer();
  final dictionaryEncoded = json.encode(dictionary);

  buffer.writeln('''// GENERATED CODE - DO NOT MODIFY BY HAND
import 'dart:convert';
import 'package:blogger_theme/blogger_theme.dart';
import 'i18n_config.dart';

/// A custom localized text component supporting runtime variables and translation.
class I18nText extends Component {
  final String key;
  final String fallback;
  final Map<String, dynamic>? variables;

  const I18nText(this.key, {required this.fallback, this.variables});

  @override
  Iterable<Component> build() {
    return [
      DomComponent(
        'span',
        attributes: {
          'data-i18n': key,
          if (variables != null) 'data-i18n-vars': json.encode(variables),
        },
        children: [Text(fallback)],
      )
    ];
  }
}

/// Flutter-style autogenerated internationalization class for type-safe theme development.
class AppI18n {
  final String locale;

  AppI18n(this.locale);

  static AppI18n get current => AppI18n(I18nConfig.defaultLocale);

  static final Map<String, Map<String, String>> _localizedValues = Map<String, Map<String, String>>.from(
    json.decode(r\'\'\'$dictionaryEncoded\'\'\').map(
      (k, v) => MapEntry(k, Map<String, String>.from(v))
    )
  );

  /// Standard translation lookup method
  String translate(String key, [Map<String, dynamic>? variables]) {
    final dict = _localizedValues[locale] ?? _localizedValues[I18nConfig.fallbackLocale] ?? {};
    final message = dict[key] ?? _localizedValues[I18nConfig.fallbackLocale]?[key] ?? key;
    if (variables == null || variables.isEmpty) {
      return message;
    }
    var result = message;
    variables.forEach((k, v) {
      result = result.replaceAll('{\$k}', v.toString());
    });
    return result;
  }
''');

  for (final entry in defaultTranslations.entries) {
    final key = entry.key;
    final value = entry.value;
    final placeholders = _extractPlaceholders(value);

    if (placeholders.isEmpty) {
      buffer.writeln('''
  // =========================================================================
  // Key: "$key"
  // =========================================================================

  /// Returns localized String fallback: "$value"
  String get $key => translate('$key');

  /// Returns localized self-translating Component fallback: "$value"
  Component get ${key}Component => I18nText('$key', fallback: translate('$key'));
''');
    } else {
      final params = placeholders.map((p) => 'required dynamic $p').join(', ');
      final varsMap = placeholders.map((p) => "'$p': $p").join(', ');
      buffer.writeln('''
  // =========================================================================
  // Key: "$key"
  // =========================================================================

  /// Returns localized String fallback: "$value" with dynamic variable substitutions
  String $key({$params}) {
    return translate('$key', {$varsMap});
  }

  /// Returns localized self-translating Component fallback: "$value"
  Component ${key}Component({$params}) {
    return I18nText(
      '$key',
      fallback: translate('$key', {$varsMap}),
      variables: {$varsMap},
    );
  }
''');
    }
  }

  buffer.writeln('}');

  final file = File('bin/i18n/app_internationalization.dart');
  file.createSync(recursive: true);
  file.writeAsStringSync(buffer.toString());
  print('Successfully generated Flutter-style bin/i18n/app_internationalization.dart!');
}

List<String> _extractPlaceholders(String text) {
  final regExp = RegExp(r'\{(\w+)');
  final matches = regExp.allMatches(text);
  return matches.map((m) => m.group(1)!).toSet().toList();
}
