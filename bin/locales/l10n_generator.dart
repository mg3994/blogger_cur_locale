import 'dart:convert';
import 'dart:io';
import 'package:path/path.dart' as p;
import 'config.dart';

/// Generates the client-side JavaScript localization dictionary and helpers.
String generateL10nScript() {
  final l10nDir = Directory('l10n');
  final Map<String, Map<String, String>> dictionary = {};
  final Set<String> allKeys = {};

  if (l10nDir.existsSync()) {
    final files = l10nDir.listSync().whereType<File>();
    for (final file in files) {
      final name = p.basename(file.path);
      if (name.endsWith('.arb')) {
        try {
          final content = file.readAsStringSync();
          final data = json.decode(content);
          if (data is Map) {
            final locale = data['@@locale'] ?? name.replaceAll('intl_', '').replaceAll('.arb', '');

            // Only process if it is in our configured supported locales list
            if (L10nConfig.supportedLocales.contains(locale)) {
              final Map<String, String> translations = {};
              for (final entry in data.entries) {
                final key = entry.key;
                final value = entry.value;
                if (!key.startsWith('@') && value is String) {
                  translations[key] = value;
                  allKeys.add(key);
                }
              }
              dictionary[locale] = translations;
            }
          }
        } catch (e) {
          print('Warning: Failed to parse ARB file ${file.path}: $e');
        }
      }
    }
  }

  // Ensure default/fallback locale is present in dictionary
  if (dictionary.isEmpty) {
    dictionary[L10nConfig.fallbackLocale] = {
      'session_settings': 'Session Settings',
    };
    allKeys.add('session_settings');
  }

  final dictionaryJson = json.encode(dictionary);
  final currencySymbolsJson = json.encode(L10nConfig.currencySymbols);

  // Generate type-safe/named JS methods on AppLocalizations for each key
  final StringBuffer jsMethods = StringBuffer();
  for (final key in allKeys) {
    jsMethods.writeln('''
    $key: function(vars) {
      return this.translate('$key', vars);
    },''');
  }

  return '''
(function() {
  const l10nDictionary = $dictionaryJson;
  const rtlLocales = ['ar', 'he', 'fa', 'ur', 'syr', 'dv', 'yi'];

  // Global AppLocalizations Engine
  window.AppLocalizations = {
    getLocale: function() {
      return localStorage.getItem('antinna-locale') || '${L10nConfig.defaultLocale}';
    },

    getCurrency: function() {
      return localStorage.getItem('antinna-currency') || '${L10nConfig.defaultCurrency}';
    },

    // 1. Core Translation with recursive ICU Message formatting
    translate: function(key, vars = {}) {
      const locale = this.getLocale();
      const dict = l10nDictionary[locale] || l10nDictionary['${L10nConfig.fallbackLocale}'] || {};
      const msg = dict[key] || l10nDictionary['${L10nConfig.fallbackLocale}'][key] || key;
      return this.formatMessage(msg, vars);
    },

    // Autogenerated typed methods on AppLocalizations for ARB keys
$jsMethods

    // ICU Message recursive parser
    formatMessage: function(msg, vars = {}) {
      if (typeof msg !== 'string') return '';

      const self = this;
      function parse(text) {
        let openBrace = -1;
        let braceCount = 0;
        for (let i = 0; i < text.length; i++) {
          if (text[i] === '{') {
            if (braceCount === 0) openBrace = i;
            braceCount++;
          } else if (text[i] === '}') {
            braceCount--;
            if (braceCount === 0 && openBrace !== -1) {
              const inner = text.substring(openBrace + 1, i);
              const prefix = text.substring(0, openBrace);
              const suffix = text.substring(i + 1);
              const result = evaluateExpression(inner, vars);
              return parse(prefix + result + suffix);
            }
          }
        }
        return text;
      }

      function evaluateExpression(expr, variables) {
        const parts = expr.split(',');
        const varName = parts[0].trim();
        if (parts.length === 1) {
          return variables[varName] !== undefined ? variables[varName] : '{' + varName + '}';
        }

        const type = parts[1].trim();
        const remaining = parts.slice(2).join(',').trim();

        if (type === 'plural' || type === 'select') {
          const cases = {};
          let caseOpen = -1;
          let caseBraceCount = 0;
          let currentCaseName = '';

          for (let i = 0; i < remaining.length; i++) {
            if (remaining[i] === '{') {
              if (caseBraceCount === 0) {
                caseOpen = i;
                currentCaseName = remaining.substring(0, i).trim();
              }
              caseBraceCount++;
            } else if (remaining[i] === '}') {
              caseBraceCount--;
              if (caseBraceCount === 0 && caseOpen !== -1) {
                cases[currentCaseName] = remaining.substring(caseOpen + 1, i);
                caseOpen = -1;
              }
            }
          }

          const val = variables[varName];
          if (type === 'plural') {
            const exactCase = '=' + val;
            if (cases[exactCase] !== undefined) {
              return parse(cases[exactCase].replace(new RegExp('\\\\{' + varName + '\\\\}', 'g'), val));
            }

            const locale = self.getLocale();
            const pr = new Intl.PluralRules(locale);
            const rule = pr.select(val);

            if (cases[rule] !== undefined) {
              return parse(cases[rule].replace(new RegExp('\\\\{' + varName + '\\\\}', 'g'), val));
            }
            return parse(cases['other'] || '');
          } else {
            // select
            if (cases[val] !== undefined) {
              return parse(cases[val]);
            }
            return parse(cases['other'] || '');
          }
        }
        return '{' + expr + '}';
      }

      return parse(msg);
    },

    // 2. ICU Number, Percentage & Scientific Formatting
    formatDecimal: function(val, fractionDigits = 2) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, {
        minimumFractionDigits: fractionDigits,
        maximumFractionDigits: fractionDigits
      }).format(val);
    },

    formatCompact: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { notation: 'compact' }).format(val);
    },

    formatPercent: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { style: 'percent' }).format(val);
    },

    formatScientific: function(val) {
      const locale = this.getLocale();
      return new Intl.NumberFormat(locale, { notation: 'scientific' }).format(val);
    },

    // 3. Currency & Financial Formatting
    formatCurrency: function(val, currencyCode) {
      const locale = this.getLocale();
      const code = currencyCode || this.getCurrency();
      return new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: code
      }).format(val);
    },

    // 4. ICU Date & Time Formatting
    formatDate: function(date, options = { year: 'numeric', month: 'long', day: 'numeric' }) {
      const locale = this.getLocale();
      const d = typeof date === 'string' || typeof date === 'number' ? new Date(date) : date;
      return new Intl.DateTimeFormat(locale, options).format(d);
    },

    formatTime: function(date, use24Hour = false) {
      const locale = this.getLocale();
      const d = typeof date === 'string' || typeof date === 'number' ? new Date(date) : date;
      return new Intl.DateTimeFormat(locale, {
        hour: 'numeric',
        minute: 'numeric',
        hour12: !use24Hour
      }).format(d);
    },

    formatRelativeTime: function(val, unit = 'day') {
      const locale = this.getLocale();
      return new Intl.RelativeTimeFormat(locale, { numeric: 'auto' }).format(val, unit);
    }
  };

  // Helper backward-compatibility reference
  window.AntinnaL10nHelper = {
    getLocale: function() { return window.AppLocalizations.getLocale(); },
    getCurrency: function() { return window.AppLocalizations.getCurrency(); },
    formatPrice: function(price, currency = null) { return window.AppLocalizations.formatCurrency(price, currency); }
  };

  window.translateDOM = function() {
    const currentLocale = localStorage.getItem('antinna-locale') || '${L10nConfig.defaultLocale}';
    const dict = l10nDictionary[currentLocale] || l10nDictionary['${L10nConfig.fallbackLocale}'] || {};

    // 1. Translate elements with data-l10n
    document.querySelectorAll('[data-l10n]').forEach(el => {
      const key = el.getAttribute('data-l10n');
      if (dict[key]) {
        if (el.textContent !== dict[key]) {
          el.textContent = dict[key];
        }
      }
    });

    // 2. Translate placeholders with data-l10n-placeholder
    document.querySelectorAll('[data-l10n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-l10n-placeholder');
      if (dict[key]) {
        if (el.getAttribute('placeholder') !== dict[key]) {
          el.setAttribute('placeholder', dict[key]);
        }
      }
    });

    // 3. Sync language selector values (both modal and sidebar)
    const langSelectors = ['language-selector', 'sidebar-language-selector'];
    langSelectors.forEach(id => {
      const select = document.getElementById(id);
      if (select && select.value !== currentLocale) {
        select.value = currentLocale;
      }
    });

    // 4. Sync currency selector values (both modal and sidebar)
    const currentCurrency = localStorage.getItem('antinna-currency') || '${L10nConfig.defaultCurrency}';
    const currSelectors = ['currency-selector', 'sidebar-currency-selector'];
    currSelectors.forEach(id => {
      const select = document.getElementById(id);
      if (select && select.value !== currentCurrency) {
        select.value = currentCurrency;
      }
    });
  };

  window.setLanguage = function(lang) {
    localStorage.setItem('antinna-locale', lang);
    document.documentElement.setAttribute('lang', lang);

    // Automatic RTL text direction layout support
    if (rtlLocales.indexOf(lang) !== -1) {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
    }

    window.translateDOM();
  };

  window.setCurrency = function(curr) {
    localStorage.setItem('antinna-currency', curr);
    const htmlEl = document.documentElement;

    // Clean old currency classes
    const classesToRemove = [];
    htmlEl.classList.forEach(cls => {
      if (cls.startsWith('currency-')) {
        classesToRemove.push(cls);
      }
    });
    classesToRemove.forEach(cls => htmlEl.classList.remove(cls));

    htmlEl.classList.add('currency-' + curr.toLowerCase());

    if (window.updatePrices) {
      window.updatePrices();
    }
  };

  window.updatePrices = function() {
    // Left customizable for you to handle Blog1 content dynamically as you prefer!
    if (typeof window.onCurrencyOrLocaleChange === 'function') {
      window.onCurrencyOrLocaleChange();
    }
  };

  // Run on DOMContentLoaded and observe future mutations
  document.addEventListener('DOMContentLoaded', () => {
    window.translateDOM();
    if (window.updatePrices) {
      window.updatePrices();
    }

    const observer = new MutationObserver(() => {
      window.translateDOM();
      if (window.updatePrices) {
        window.updatePrices();
      }
    });
    observer.observe(document.body, { childList: true, subtree: true });
  });
})();
''';
}
